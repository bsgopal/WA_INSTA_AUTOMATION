function nameFor(hex) {
  const h = '#' + hex.toLowerCase();
  if (CUSTOM[h]) return CUSTOM[h].name;
  return 'c' + hex.toLowerCase();
}

const entries = [...unique]
  .sort((a, b) => a.localeCompare(b))
  .map((hex) => ({ hex: '#' + hex, name: nameFor(hex) }));

let out = `// Centralized color palette - edit/add here to re-brand the whole UI.\n// Auto-generated from source scan; keep names stable.\n\nexport const colors = {\n`;
for (const { hex, name } of entries) {
  out += `  ${name}: '${hex}',\n`;
}
out += '};\n';

const dest = path.join(srcDir, 'config', 'colors.js');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`wrote ${entries.length} colors -> ${dest}`);